"""Generate calendar-derived features for Part C feature engineering.

Intended project location::

    app/ml/feature_engineering/calendar_features.py

Features generated by this module:

- ``is_weekend``
  Binary indicator: Monday-Friday = 0, Saturday-Sunday = 1.

- ``day_of_week``
  Integer weekday index using pandas convention:
  Monday = 0 through Sunday = 6.

- ``day_sin``
  Sine encoding of the weekday cycle.

- ``day_cos``
  Cosine encoding of the weekday cycle.

Rules:

- only the configured timestamp column is used;
- KPI values, source preparation, status labels, and cleaning are irrelevant;
- timestamps are parsed for calculation but the source dataframe is unchanged;
- requested features are generated exactly in request order;
- generated output preserves the source row count and index; and
- time-of-day bucket and cyclical features remain the responsibility of
  ``time_features.py``.
"""

from __future__ import annotations

from math import pi
from typing import Final

import numpy as np
import pandas as pd

from app.schemas.feature_engineering import CalendarFeatureRequest

from .common import require_columns


DAYS_PER_WEEK: Final = 7


def _prepare_timestamps(
    site_dataframe: pd.DataFrame,
    *,
    timestamp_column: str,
) -> pd.Series:
    """Return one validated datetime Series aligned with the site dataframe.

    Timeline validity and exact frequency should already be checked by
    ``feature_validation.py``. This function performs a defensive parse so the
    generator fails clearly when called independently with unusable timestamps.
    """

    if not isinstance(site_dataframe, pd.DataFrame):
        raise TypeError(
            "site_dataframe must be a pandas DataFrame."
        )

    if not isinstance(timestamp_column, str) or not timestamp_column.strip():
        raise ValueError(
            "timestamp_column must be a non-empty string."
        )

    require_columns(
        site_dataframe,
        [timestamp_column],
        context="calendar-feature generation",
    )

    if site_dataframe.empty:
        raise ValueError(
            "Cannot generate calendar features from an empty site dataframe."
        )

    timestamps = pd.to_datetime(
        site_dataframe[timestamp_column],
        errors="coerce",
    )

    invalid_mask = timestamps.isna()

    if invalid_mask.any():
        invalid_indices = (
            timestamps.index[invalid_mask]
            .tolist()[:10]
        )

        raise ValueError(
            f"Timestamp column '{timestamp_column}' contains "
            f"{int(invalid_mask.sum()):,} missing or invalid values. "
            f"First invalid indices: {invalid_indices}"
        )

    timestamps.index = site_dataframe.index
    timestamps.name = timestamp_column

    return timestamps


def _validate_output_alignment(
    output: pd.DataFrame,
    *,
    expected_index: pd.Index,
) -> None:
    """Defensively verify row, index, and column preservation rules."""

    if len(output) != len(expected_index):
        raise RuntimeError(
            "Calendar-feature generation unexpectedly changed the row count."
        )

    if not output.index.equals(expected_index):
        raise RuntimeError(
            "Calendar-feature generation unexpectedly changed the source "
            "index."
        )

    if output.columns.empty:
        raise RuntimeError(
            "Calendar-feature generation produced no feature columns."
        )

    if output.columns.has_duplicates:
        duplicates = (
            output.columns[
                output.columns.duplicated()
            ]
            .tolist()
        )

        raise RuntimeError(
            "Calendar-feature generation produced duplicate columns: "
            f"{duplicates}"
        )


def generate_calendar_features(
    request: CalendarFeatureRequest,
    *,
    site_dataframe: pd.DataFrame,
    timestamp_column: str,
) -> pd.DataFrame:
    """Generate requested calendar features for one timestamp-ordered site.

    Weekday-cycle formulas::

        angle = 2 * pi * day_of_week / 7
        day_sin = sin(angle)
        day_cos = cos(angle)

    Args:
        request:
            Validated ``calendar`` feature request.
        site_dataframe:
            One valid site dataframe already ordered by timestamp.
        timestamp_column:
            Resolved physical timestamp-column name from
            ``DatasetInputConfig``.

    Returns:
        pd.DataFrame:
            Requested numeric calendar features aligned with the source site.
    """

    if not isinstance(request, CalendarFeatureRequest):
        raise TypeError(
            "generate_calendar_features requires CalendarFeatureRequest; "
            f"received {type(request).__name__}."
        )

    timestamps = _prepare_timestamps(
        site_dataframe,
        timestamp_column=timestamp_column,
    )

    day_of_week = timestamps.dt.dayofweek.astype("int64")
    angle = (
        2.0
        * pi
        * day_of_week.astype("float64")
        / float(DAYS_PER_WEEK)
    )

    output = pd.DataFrame(
        index=site_dataframe.index,
    )

    for feature_name in request.features:
        if feature_name == "is_weekend":
            output[feature_name] = (
                day_of_week >= 5
            ).astype("int8")

        elif feature_name == "day_of_week":
            output[feature_name] = day_of_week

        elif feature_name == "day_sin":
            output[feature_name] = np.sin(
                angle
            ).astype("float64")

        elif feature_name == "day_cos":
            output[feature_name] = np.cos(
                angle
            ).astype("float64")

        else:
            # The schema should prevent this branch. It remains as a defensive
            # runtime guard for direct/internal calls.
            raise ValueError(
                "Unsupported calendar feature: "
                f"{feature_name!r}"
            )

    _validate_output_alignment(
        output,
        expected_index=site_dataframe.index,
    )

    return output


__all__ = [
    "DAYS_PER_WEEK",
    "generate_calendar_features",
]